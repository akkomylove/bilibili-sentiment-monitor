def all_sector_terms() -> list[str]:
    """返回所有板块术语的扁平化列表（用于关键词过滤）"""
    terms: list[str] = []
    for sector_words in SECTOR_TERMS.values():
        terms.extend(sector_words)
    return terms


def is_sector_term(word: str) -> bool:
    """判断一个词是否属于某个板块的术语"""
    for sector_words in SECTOR_TERMS.values():
        if word in sector_words:
            return True
    return False


def detect_sector(text: str) -> str | None:
    """根据文本内容判断属于哪个板块

    Returns:
        板块名称（半导体/光通信/光芯片），若不匹配则返回 None
    """
    for sector, words in SECTOR_TERMS.items():
        for w in words:
            if w in text:
                return sector
    return None


def _register_jieba_dict() -> None:
    """将 SECTOR_TERMS 注册到 jieba 用户词典，确保分词时不被拆开

    例：'中芯国际' 不会被拆成 ['中芯', '国际']
    """
    for sector, words in SECTOR_TERMS.items():
        for w in words:
            # jieba 自带词频机制，频次 100 足以覆盖 B 站评论场景
            jieba.add_word(w, freq=100, tag=sector)


# 模块导入时自动注册
_register_jieba_dict()
